import { zipSync } from 'fflate'
import { describe, expect, it } from 'vitest'
import {
  commentHeuristics,
  countLines,
  isGenerated,
  kindOf,
  slopFindings,
  testStats,
} from './metrics/code-rules.ts'
import { patchAdditions, scanFiles, unpackZipball } from './metrics/codebase.ts'

const rules = (text: string) => slopFindings(text).map((f) => f.rule)

describe('kindOf', () => {
  it('separates production code, tests and feature files', () => {
    expect(kindOf('apps/api/src/Orders/Order.cs')).toBe('source')
    expect(kindOf('apps/web/src/views/home.tsx')).toBe('source')
    expect(kindOf('apps/web/src/views/home.test.tsx')).toBe('test')
    expect(kindOf('tests/Numa.Api.Tests/OrdersTests.cs')).toBe('test')
    expect(kindOf('apps/api/tests/Orders.IntegrationTests/Fixture.cs')).toBe('test')
    expect(kindOf('specs/orders.feature')).toBe('feature')
  })

  it('leaves out vendored, installed and generated paths', () => {
    expect(kindOf('apps/web/src/components/ui/button.tsx')).toBeNull()
    expect(kindOf('.github/actions/verify/verify.mjs')).toBeNull()
    expect(kindOf('.opencode/plugins/pc-system-reminders.js')).toBeNull()
    expect(kindOf('apps/api/src/Migrations/20260101_Init.cs')).toBeNull()
    expect(kindOf('apps/web/next-env.d.ts')).toBeNull()
    expect(kindOf('README.md')).toBeNull()
  })

  it('recognises generated headers', () => {
    expect(isGenerated('// <auto-generated>\nclass A {}')).toBe(true)
    expect(isGenerated('class A {}')).toBe(false)
  })
})

describe('countLines', () => {
  it('counts line, doc and block comments apart from code', () => {
    const text =
      '// a\nconst a = 1\n/**\n * doc\n */\nfunction f() {}\n\n/// <summary>x</summary>\n'
    expect(countLines(text)).toEqual({ codeLines: 2, commentLines: 5 })
  })
})

describe('slopFindings', () => {
  it('finds the Atlas shapes', () => {
    expect(rules('// =====\nconst a = 1')).toEqual(['banner'])
    expect(rules('#region Helpers\n#endregion')).toEqual(['region', 'region'])
    expect(rules('// TODO fix later')).toEqual(['untracked-todo'])
    expect(rules('// TODO fix later, see #12')).toEqual([])
    expect(rules("const s = '// TODO later'")).toEqual([])
    expect(rules('// const old = compute();\n// return old;')).toEqual(['commented-out-code'])
    expect(rules('// not sure if this is right')).toEqual(['apologetic'])
  })

  it('finds C# docs that only repeat the member name', () => {
    expect(rules('/// <summary>Gets the user id.</summary>\npublic int UserId { get; }')).toEqual([
      'restating-summary',
    ])
    expect(
      rules(
        '/// <summary>Widening the column keeps the audit chain valid.</summary>\npublic int UserId;',
      ),
    ).toEqual([])
  })

  it('finds JSDoc that only repeats the declaration', () => {
    expect(rules('/** The user id. */\nexport const userId = 1')).toEqual(['restating-jsdoc'])
    expect(rules('/**\n * Gets the user name.\n */\nfunction getUserName() {}')).toEqual([
      'restating-jsdoc',
    ])
    expect(
      rules(
        '/** Returns null on 404 so a missing resource degrades instead of throwing. */\nexport function get() {}',
      ),
    ).toEqual([])
  })
})

describe('commentHeuristics', () => {
  it('counts incident stories, essays and docs on internal symbols', () => {
    const text = [
      'import x from "y"',
      '// Numa #659 was closed one second after a comment dispatched refine.',
      'const a = 1',
      '// one',
      '// two',
      '// three',
      '// four',
      '// five',
      'const b = 2',
      '/** Internal helper. */',
      'function helper() {}',
      '/** Public helper. */',
      'export function api() {}',
    ].join('\n')
    expect(commentHeuristics(text)).toEqual({ history: 1, essay: 1, internalDoc: 1 })
  })

  it('does not count a file header as an essay', () => {
    const header = ['// 1', '// 2', '// 3', '// 4', '// 5', 'const a = 1'].join('\n')
    expect(commentHeuristics(header).essay).toBe(0)
  })
})

describe('testStats', () => {
  it('counts TypeScript cases and the suspicious ones', () => {
    const text = [
      "it('adds', () => { expect(add(1, 1)).toBe(2) })",
      "it.skip('skipped', () => { expect(1).toBe(1) })",
      "it.only('focused', () => { expect(1).toBe(1) })",
      "test('no assertion', () => { add(1, 1) })",
      "it('snapshot', () => { expect(render()).toMatchSnapshot() })",
      "it('only mocks', () => { run(); expect(spy).toHaveBeenCalled() })",
      "it.todo('later')",
    ].join('\n')
    expect(testStats('a.test.ts', text)).toEqual({
      cases: 6,
      skipped: 1,
      focused: 1,
      snapshot: 1,
      noAssertion: 1,
      mockOnly: 1,
    })
  })

  it('counts xUnit cases', () => {
    const text = [
      '[Fact]',
      'public void Adds() { Assert.Equal(2, Add(1, 1)); }',
      '[Theory]',
      '[InlineData(1)]',
      'public void Fluent(int a) { a.Should().Be(1); }',
      '[Fact(Skip = "flaky")]',
      'public void Skipped() { Assert.True(true); }',
      '[Fact]',
      'public void Calls() { sut.Run(); repo.Received(1).Save(); }',
    ].join('\n')
    expect(testStats('OrdersTests.cs', text)).toEqual({
      cases: 4,
      skipped: 1,
      focused: 0,
      snapshot: 0,
      noAssertion: 0,
      mockOnly: 1,
    })
  })
})

describe('scanFiles', () => {
  it('summarises production comments and tests separately', () => {
    const code = scanFiles(
      [
        { path: 'src/a.ts', text: '// TODO later\nconst a = 1\nconst b = 2\n' },
        { path: 'src/b.ts', text: 'const c = 3\n' },
        { path: 'src/a.test.ts', text: "it('a', () => { expect(1).toBe(1) })\n" },
        { path: 'specs/a.feature', text: 'Feature: a\n  Scenario: one\n  Scenario: two\n' },
        { path: 'src/gen.ts', text: '// @generated\nconst g = 1\n' },
      ],
      'main',
      'abc',
    )
    expect(code.files).toEqual({ source: 2, test: 1, generated: 1 })
    expect(code.comments.codeLines).toBe(3)
    expect(code.comments.commentLines).toBe(1)
    expect(code.comments.density).toBe(0.333)
    expect(code.comments.slop.findings).toBe(1)
    expect(code.tests).toMatchObject({ files: 1, lines: 1, cases: 1, features: 1, scenarios: 2 })
    expect(code.hotspots.map((h) => h.path)).toEqual(['src/a.ts'])
  })
})

describe('unpackZipball', () => {
  it('strips the archive root, keeps only scanned files and reads the sha', () => {
    const enc = new TextEncoder()
    const zip = zipSync({
      'org-repo-abc1234/src/a.ts': enc.encode('﻿const a = 1\r\n'),
      'org-repo-abc1234/README.md': enc.encode('# readme'),
    })
    const { files, sha } = unpackZipball(zip)
    expect(sha).toBe('abc1234')
    expect(files).toEqual([{ path: 'src/a.ts', text: 'const a = 1\n' }])
  })
})

describe('patchAdditions', () => {
  it('counts only added lines, split into code, comments and tests', () => {
    const added = patchAdditions([
      { filename: 'src/a.ts', patch: '@@ -1 +1,3 @@\n-old\n+// why\n+const a = 1\n context' },
      {
        filename: 'src/a.test.ts',
        patch: "@@ -0,0 +1 @@\n+it('a', () => { expect(a).toBe(1) })",
      },
      { filename: 'README.md', patch: '+text' },
    ])
    expect(added).toEqual({ codeLines: 1, commentLines: 1, testLines: 1, testCases: 1, slop: 0 })
  })
})
